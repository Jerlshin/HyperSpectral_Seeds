"""The final report: evidence, then conclusions, then what to run next.

Written to be read by somebody who did not run the study, in the order they
need it — what was measured and under what protocol, what the numbers show,
what follows for the next experiment, and where each claim's evidence lives.
Every number is regenerable from ``analysis/*.csv``, and the report says so, so
a reader who disagrees can recompute rather than argue.

Two rules the generator keeps
─────────────────────────────
**No number without its uncertainty and its n.** A mean over folds and
replicates is printed with the spread and the count, never on its own; a table
whose cells came from one measurement says so.

**No conclusion the flags contradict.** :func:`_conclusions` reads the
critical and warning flags first and states the caveats *before* the
recommendation they qualify, rather than after it in small print. If the study
found no plateau, the report leads with that; if no method beat the random
null, it leads with that.
"""

