def build_report(cfg: BandStudyConfig, render_figures: bool = True) -> Path:
    """Assemble ``REPORT.md`` from the analysis artifacts.

    Raises:
        FileNotFoundError: The analysis stage has not run.
    """
    recommendation = bsanalysis.load_recommendation(cfg)
    flags = bsanalysis.load_flags(cfg)
    curves = _read(cfg, "curves")
    trends = _read(cfg, "trends")
    margins = _read(cfg, "null_margins")
    ranking = _read(cfg, "method_ranking")
    stability = _read(cfg, "stability")
    cross_fold = _read(cfg, "cross_fold_agreement")
    redundancy = _read(cfg, "redundancy")
    consensus = _read(cfg, "wavelength_frequency")
    confirm = bsanalysis.confirm_table(cfg)
    neural = bsneural.collect_neural(cfg)

    manifest_path = cfg.root / MANIFEST
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    splits_path = cfg.cache_dir / "splits.json"
    splits = json.loads(splits_path.read_text()) if splits_path.exists() else {}

    inputs = load_inputs(cfg, quiet=True)
    figure_paths: list[Path] = []
    if render_figures:
        mean_spectrum = np.asarray(inputs.spectra, dtype=np.float64).mean(axis=0)
        figure_paths = bsfigures.render_all(cfg, mean_spectrum=mean_spectrum)

    sections: list[str] = []
    sections += _header(cfg, manifest)
    sections += _protocol(cfg, splits)
    sections += _budget_section(cfg, curves, trends)
    sections += _method_section(cfg, ranking, margins)
    sections += _wavelength_section(
        cfg, consensus, inputs, int(recommendation.get("recommended_budget", 0))
    )
    sections += _stability_section(cfg, stability, cross_fold, redundancy)
    sections += _flags_section(flags)
    sections += _confirm_section(cfg, confirm, curves)
    sections += _neural_section(cfg, neural)
    sections += _conclusions(cfg, recommendation, flags, curves, ranking, neural)
    sections += _evidence(cfg, figure_paths)

    cfg.report_path.parent.mkdir(parents=True, exist_ok=True)
    cfg.report_path.write_text("\n".join(sections) + "\n")
    _log.info("report → %s", cfg.report_path)
    return cfg.report_path
