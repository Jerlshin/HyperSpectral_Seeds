#: The metric every table reports, taken from the analysis module so the report
#: and the decisions cannot end up describing different quantities.
METRIC = bsanalysis.METRIC


def _read(cfg: BandStudyConfig, name: str) -> pd.DataFrame:
    """One analysis table, read back without pandas' string-to-NaN coercion.

    ``keep_default_na=False`` with an explicit ``na_values=[""]`` matters here:
    the default sentinel list contains bare tokens like ``null``, ``NA`` and
    ``None``, which are perfectly good *values* in these tables — a method's
    family, a fallback reason, a free-text rationale — and silently reading them
    back as missing put ``NaN`` in the published method-comparison table where
    the word ``null_model`` belonged. Empty cells, which is what
    ``DataFrame.to_csv`` writes for a real NaN, still parse as NaN.
    """
    path = cfg.analysis_dir / f"{name}.csv"
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path, keep_default_na=False, na_values=[""])


def _fmt(value: Any, digits: int = 4) -> str:
    if value is None or (isinstance(value, float) and not np.isfinite(value)):
        return "—"
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        return f"{float(value):.{digits}f}"
    return str(value)


